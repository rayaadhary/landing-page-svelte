/**
 * Normalize a modules entry (legacy string or { name, icon }) to a uniform object.
 * @param {string | { name?: string, icon?: string }} m
 * @returns {{ name: string, icon: string }}
 */
export function normalizeModule(m) {
	if (typeof m === 'string') return { name: m, icon: '' };
	return { name: m?.name ?? '', icon: m?.icon ?? '' };
}
